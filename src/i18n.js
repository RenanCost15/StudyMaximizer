export function detectInitialLocale() {
  try {
    const saved = localStorage.getItem(LANGUAGE_STORAGE_KEY);
    if (saved && SUPPORTED_LOCALES.some(item => item.code === saved)) return saved;
  } catch { /* storage may be unavailable */ }
  const browserLocales = typeof navigator !== 'undefined' ? (navigator.languages || [navigator.language || 'pt-BR']) : ['pt-BR'];
  return browserLocales.some(language => String(language).toLowerCase().startsWith('en')) ? 'en' : 'pt-BR';
}

let activeLocale = 'pt-BR';

export function setActiveLocale(locale) {
  activeLocale = SUPPORTED_LOCALES.some(item => item.code === locale) ? locale : 'pt-BR';
}

export function getActiveLocale() { return activeLocale; }

export function translate(text, locale = activeLocale) {
  if (locale !== 'en') return text;
  return EN[text] || text;
}

export function translateAuthError(error, locale = 'pt-BR', mode = 'login') {
  const code = String(error?.code || error?.name || '').toLowerCase();
  const message = String(error?.message || '').toLowerCase();
  let key = 'Não foi possível concluir a solicitação. Tente novamente.';

  if (code === 'email_not_confirmed' || message.includes('email not confirmed')) {
    key = 'Seu e-mail ainda não foi confirmado. Confira a caixa de entrada e o spam ou solicite outro e-mail de confirmação.';
  } else if (code === 'user_already_confirmed' || message.includes('user already confirmed') || message.includes('email already confirmed')) {
    key = 'Este e-mail já está confirmado. Faça login ou redefina sua senha.';
  } else if (['user_already_exists', 'email_exists'].includes(code) || message.includes('user already registered') || message.includes('email address already exists')) {
    key = 'Este e-mail já está cadastrado. Faça login; se a confirmação estiver pendente, solicite um novo e-mail.';
  } else if (code === 'invalid_credentials' || message.includes('invalid login credentials') || message.includes('invalid credentials')) {
    key = 'E-mail ou senha incorretos. Confira os dados e tente novamente. Se ainda não tiver conta, crie uma.';
  } else if (code === 'weak_password' || message.includes('password should be at least') || message.includes('weak password')) {
    key = 'A senha informada não atende aos requisitos de segurança. Escolha uma senha mais forte.';
  } else if (['over_request_rate_limit', 'over_email_send_rate_limit', 'too_many_requests'].includes(code) || message.includes('rate limit') || error?.status === 429) {
    key = 'Muitas tentativas. Aguarde alguns minutos e tente novamente.';
  } else if (code === 'email_address_invalid' || message.includes('invalid email')) {
    key = 'Informe um endereço de e-mail válido.';
  } else if (mode === 'signup' && message.includes('password')) {
    key = 'A senha informada não atende aos requisitos de segurança. Escolha uma senha mais forte.';
  }

  return translate(key, locale);
}
